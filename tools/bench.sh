#!/usr/bin/env bash
# bench.sh [RATE] - build a single ROM that times every demos/*.dsp on the N64.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# Which faust? Homebrew's aborts on startup here (its LLVM wants libz3.4.16,
# which brew cleanup removed, and Homebrew refuses to rebuild LLVM on this
# machine - "Tier 3 configuration"). Fall back to the locally built compiler.
FAUST="${FAUST:-faust}"
( "$FAUST" --version >/dev/null 2>&1 ) || { echo "$(basename "$0"): no working faust" >&2; exit 1; }

SR="${1:-22050}"
: "${N64_INST:=$HOME/n64-toolchain}"
export N64_INST
[ -f "$N64_INST/include/n64.mk" ] || { echo "bench: no toolchain at $N64_INST" >&2; exit 1; }
FAUSTINC="$("$FAUST" --includedir 2>/dev/null || echo /usr/local/include)"
[ -d "$FAUSTINC/faust" ] || FAUSTINC=/usr/local/include

W="$HERE/build/bench"
rm -rf "$W"; mkdir -p "$W"
cp "$HERE/tools/bench.c" "$W/bench.c"

NAMES=()
for f in "$HERE"/demos/*.dsp; do
    n="$(basename "$f" .dsp)"
    i="d_$(printf '%s' "$n" | tr -c 'A-Za-z0-9_' '_')"
    "$FAUST" -lang c -ftz 1 -cn "$i" -o "$W/$i.c" "$f"
    NAMES+=("$n:$i")
done

{
    echo '/* generated by tools/bench.sh - do not edit */'
    echo 'typedef struct { const char *name; void *(*nw)(void); void (*in)(void*,int);'
    echo '  void (*cp)(void*,int,float**,float**); int (*no)(void*); int (*ni)(void*); } bench_entry;'
    for e in "${NAMES[@]}"; do
        i="${e#*:}"
        echo "extern void *new$i(void);"
        echo "extern void init$i(void*,int);"
        echo "extern void compute$i(void*,int,float**,float**);"
        echo "extern int getNumOutputs$i(void*);"
        echo "extern int getNumInputs$i(void*);"
    done
    echo 'const bench_entry BENCH[] = {'
    for e in "${NAMES[@]}"; do
        n="${e%%:*}"; i="${e#*:}"
        echo "  { \"$n\", new$i, init$i, compute$i, getNumOutputs$i, getNumInputs$i },"
    done
    echo '};'
    echo "const int BENCH_COUNT = ${#NAMES[@]};"
} > "$W/bench_table.c"

OBJS="\$(BUILD_DIR)/bench.o \$(BUILD_DIR)/bench_table.o"
for e in "${NAMES[@]}"; do OBJS="$OBJS \$(BUILD_DIR)/${e#*:}.o"; done

cat > "$W/Makefile" <<MK
BUILD_DIR = obj
include \$(N64_INST)/include/n64.mk
N64_C_AND_CXX_FLAGS += -I$FAUSTINC -DBENCH_SR=$SR
N64_C_AND_CXX_FLAGS += -include faust/gui/CInterface.h
N64_C_AND_CXX_FLAGS += -Wno-error=unused-but-set-variable
all: bench.z64
.PHONY: all
OBJS = $OBJS
\$(BUILD_DIR)/bench.elf: \$(OBJS)
bench.z64: N64_ROM_TITLE = "FAUST64 BENCH"
MK

make -C "$W" -s
cp "$W/bench.z64" "$HERE/demos/bench.z64"
echo "bench: demos/bench.z64  (${#NAMES[@]} demos @ ${SR} Hz)"
